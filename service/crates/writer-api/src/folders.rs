//! Creating, reading, renaming, moving, and deleting folders.

use axum::extract::State;
use axum::http::StatusCode;
use axum::response::Response;
use serde::{Deserialize, Serialize};
use utoipa::ToSchema;
use writer_domain::{self as domain, Item, ItemId, NewItem, Title, Violation};
use writer_storage::Created;

use crate::extract::{Json, Path};
use crate::problem::{BodyProblems, Problem};
use crate::workspace::{
    ItemKind, ReplacePositionRequest, ReplaceTitleRequest, Store, created_response, delete,
    path_id, place, placement, rename, replayed, required_nullable,
};

/// A folder, which holds folders and documents.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, ToSchema)]
#[serde(rename_all = "camelCase")]
pub struct Folder {
    pub id: String,
    /// The containing folder, or `null` at the top level.
    #[schema(required = true)]
    pub parent_id: Option<String>,
    pub title: String,
}

impl From<domain::Folder> for Folder {
    fn from(folder: domain::Folder) -> Self {
        Self {
            id: folder.id.to_string(),
            parent_id: folder.parent_id.map(|id| id.to_string()),
            title: folder.title.into_string(),
        }
    }
}

impl TryFrom<Item> for Folder {
    type Error = Problem;

    fn try_from(item: Item) -> Result<Self, Problem> {
        match item {
            Item::Folder(folder) => Ok(folder.into()),
            Item::Document(_) => Err(Problem::internal_error()),
        }
    }
}

/// A folder to create with a client-generated identifier.
#[derive(Debug, Deserialize, ToSchema)]
#[serde(rename_all = "camelCase", deny_unknown_fields)]
pub(crate) struct CreateFolderRequest {
    /// A new lowercase hyphenated UUID, generated by the client.
    pub folder_id: String,
    /// The folder to create it in, or `null` for the top level.
    #[serde(deserialize_with = "required_nullable")]
    #[schema(required = true)]
    pub parent_id: Option<String>,
    /// The sibling to create it before, or `null` for the end.
    #[serde(deserialize_with = "required_nullable")]
    #[schema(required = true)]
    pub before_id: Option<String>,
    /// 1 to 200 characters with no surrounding whitespace or control
    /// characters.
    pub title: String,
}

/// Create a folder, or return the existing folder with the same identifier.
#[utoipa::path(
    post,
    path = "/folders",
    operation_id = "createFolder",
    tag = "folders",
    request_body = CreateFolderRequest,
    responses(
        (
            status = 201,
            description = "Created the folder.",
            body = Folder,
            headers(("Location" = String, description = "The path of the new folder."))
        ),
        (
            status = 200,
            description = "A folder with this identifier already exists; nothing changed.",
            body = Folder
        ),
        (
            status = 409,
            description = "The identifier belongs to a document, or `parentId` or `beforeId` names no item there.",
            body = Problem,
            content_type = "application/problem+json"
        ),
        (
            status = 500,
            description = "The service failed unexpectedly.",
            body = Problem,
            content_type = "application/problem+json"
        ),
        BodyProblems,
    )
)]
pub(crate) async fn create_folder(
    State(store): State<Store>,
    Json(body): Json<CreateFolderRequest>,
) -> Result<Response, Problem> {
    let id =
        ItemId::parse(&body.folder_id).map_err(|_| Violation::Identifier(domain::ItemKind::Folder));
    let (id, title) = match (id, Title::parse(body.title)) {
        (Ok(id), Ok(title)) => (id, title),
        (id, title) => {
            return Err(Problem::violations(
                [id.err(), title.err()].into_iter().flatten(),
            ));
        }
    };
    let location = format!("/api/v1/folders/{id}");
    let created = match placement(body.parent_id, body.before_id) {
        Some(placement) => store.create(NewItem::folder(id, title, placement)).await?,
        None => Created::Existing(replayed(&store, id, ItemKind::Folder).await?),
    };
    let folder = Folder::try_from(created.item().clone())?;
    Ok(created_response(&created, location, folder))
}

/// Read a folder.
#[utoipa::path(
    get,
    path = "/folders/{folderId}",
    operation_id = "getFolder",
    tag = "folders",
    params(("folderId" = String, Path, description = "The folder's identifier.")),
    responses(
        (status = 200, description = "The folder.", body = Folder),
        (
            status = 404,
            description = "No folder has the identifier.",
            body = Problem,
            content_type = "application/problem+json"
        ),
        (
            status = 500,
            description = "The service failed unexpectedly.",
            body = Problem,
            content_type = "application/problem+json"
        ),
    )
)]
pub(crate) async fn get_folder(
    State(store): State<Store>,
    Path(folder_id): Path<String>,
) -> Result<Json<Folder>, Problem> {
    let item = store
        .item(path_id(&folder_id)?, domain::ItemKind::Folder)
        .await?;
    Ok(Json(item.try_into()?))
}

/// Rename a folder.
#[utoipa::path(
    put,
    path = "/folders/{folderId}/title",
    operation_id = "replaceFolderTitle",
    tag = "folders",
    params(("folderId" = String, Path, description = "The folder's identifier.")),
    request_body = ReplaceTitleRequest,
    responses(
        (status = 200, description = "The renamed folder.", body = Folder),
        (
            status = 404,
            description = "No folder has the identifier.",
            body = Problem,
            content_type = "application/problem+json"
        ),
        (
            status = 500,
            description = "The service failed unexpectedly.",
            body = Problem,
            content_type = "application/problem+json"
        ),
        BodyProblems,
    )
)]
pub(crate) async fn replace_folder_title(
    State(store): State<Store>,
    Path(folder_id): Path<String>,
    Json(body): Json<ReplaceTitleRequest>,
) -> Result<Json<Folder>, Problem> {
    let item = rename(&store, &folder_id, ItemKind::Folder, body).await?;
    Ok(Json(item.try_into()?))
}

/// Move or reorder a folder with everything in it.
#[utoipa::path(
    put,
    path = "/folders/{folderId}/position",
    operation_id = "replaceFolderPosition",
    tag = "folders",
    params(("folderId" = String, Path, description = "The folder's identifier.")),
    request_body = ReplacePositionRequest,
    responses(
        (status = 200, description = "The moved folder.", body = Folder),
        (
            status = 404,
            description = "No folder has the identifier.",
            body = Problem,
            content_type = "application/problem+json"
        ),
        (
            status = 409,
            description = "`parentId` or `beforeId` names no item there, or `parentId` is the folder or inside it.",
            body = Problem,
            content_type = "application/problem+json"
        ),
        (
            status = 500,
            description = "The service failed unexpectedly.",
            body = Problem,
            content_type = "application/problem+json"
        ),
        BodyProblems,
    )
)]
pub(crate) async fn replace_folder_position(
    State(store): State<Store>,
    Path(folder_id): Path<String>,
    Json(body): Json<ReplacePositionRequest>,
) -> Result<Json<Folder>, Problem> {
    let item = place(&store, &folder_id, ItemKind::Folder, body).await?;
    Ok(Json(item.try_into()?))
}

/// Permanently delete a folder and everything in it.
#[utoipa::path(
    delete,
    path = "/folders/{folderId}",
    operation_id = "deleteFolder",
    tag = "folders",
    params(("folderId" = String, Path, description = "The folder's identifier.")),
    responses(
        (status = 204, description = "Deleted the folder and everything in it."),
        (
            status = 404,
            description = "No folder has the identifier.",
            body = Problem,
            content_type = "application/problem+json"
        ),
        (
            status = 500,
            description = "The service failed unexpectedly.",
            body = Problem,
            content_type = "application/problem+json"
        ),
    )
)]
pub(crate) async fn delete_folder(
    State(store): State<Store>,
    Path(folder_id): Path<String>,
) -> Result<StatusCode, Problem> {
    delete(&store, &folder_id, ItemKind::Folder).await
}
