/// A document's metadata and the revision of its content.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, ToSchema)]
#[serde(rename_all = "camelCase")]
pub struct Document {
    pub id: String,
    /// The containing folder, or `null` at the top level.
    #[schema(required = true)]
    pub parent_id: Option<String>,
    pub title: String,
    /// An opaque token that changes whenever the content changes; compare
    /// it only for equality.
    pub revision: String,
}

impl From<domain::Document> for Document {
    fn from(document: domain::Document) -> Self {
        Self {
            id: document.id.to_string(),
            parent_id: document.parent_id.map(|id| id.to_string()),
            title: document.title.into_string(),
            revision: document.revision.as_str().to_owned(),
        }
    }
}

impl TryFrom<Item> for Document {
    type Error = Problem;

    fn try_from(item: Item) -> Result<Self, Problem> {
        match item {
            Item::Document(document) => Ok(document.into()),
            Item::Folder(_) => Err(Problem::internal_error()),
        }
    }
}

/// A document's content and its revision.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, ToSchema)]
#[serde(rename_all = "camelCase")]
pub struct DocumentContent {
    /// The document's Markdown, exactly as stored.
    pub markdown: String,
    pub revision: String,
}

/// A document to create with a client-generated identifier.
#[derive(Debug, Deserialize, ToSchema)]
#[serde(rename_all = "camelCase", deny_unknown_fields)]
pub(crate) struct CreateDocumentRequest {
    /// A new lowercase hyphenated UUID, generated by the client.
    pub document_id: String,
    /// The folder to create it in, or `null` for the top level.
    #[serde(deserialize_with = "required_nullable")]
    #[schema(required = true)]
    pub parent_id: Option<String>,
    /// The sibling to create it before, or `null` for the end.
    #[serde(deserialize_with = "required_nullable")]
    #[schema(required = true)]
    pub before_id: Option<String>,
    /// 1 to 200 characters with no surrounding whitespace or control
    /// characters.
    pub title: String,
    /// The initial content, at most 1 MiB of UTF-8 without U+0000; empty
    /// when omitted.
    #[serde(default)]
    #[schema(nullable = false)]
    pub markdown: Option<String>,
}

/// A whole new content for a document, checked against the revision the
/// client's edits started from.
#[derive(Debug, Deserialize, ToSchema)]
#[serde(rename_all = "camelCase", deny_unknown_fields)]
pub(crate) struct ReplaceContentRequest {
    /// At most 1 MiB of UTF-8 without U+0000.
    pub markdown: String,
    /// The revision of the content the edits started from.
    pub base_revision: String,
}

/// Create a document, or return the existing document with the same
/// identifier.
#[utoipa::path(
    post,
    path = "/documents",
    operation_id = "createDocument",
    tag = "documents",
    request_body = CreateDocumentRequest,
    responses(
        (
            status = 201,
            description = "Created the document.",
            body = Document,
            headers(("Location" = String, description = "The path of the new document."))
        ),
        (
            status = 200,
            description = "A document with this identifier already exists; nothing changed.",
            body = Document
        ),
        (
            status = 409,
            description = "The identifier belongs to a folder, or `parentId` or `beforeId` names no item there.",
            body = Problem,
            content_type = "application/problem+json"
        ),
        (
            status = 500,
            description = "The service failed unexpectedly.",
            body = Problem,
            content_type = "application/problem+json"
        ),
        BodyProblems,
    )
)]
pub(crate) async fn create_document(
    State(store): State<Store>,
    Json(body): Json<CreateDocumentRequest>,
) -> Result<Response, Problem> {
    let id = ItemId::parse(&body.document_id)
        .map_err(|_| Violation::Identifier(domain::ItemKind::Document));
    let title = Title::parse(body.title);
    let markdown = Markdown::parse(body.markdown.unwrap_or_default());
    let (id, title, markdown) = match (id, title, markdown) {
        (Ok(id), Ok(title), Ok(markdown)) => (id, title, markdown),
        (id, title, markdown) => {
            return Err(Problem::violations(
                [id.err(), title.err(), markdown.err()]
                    .into_iter()
                    .flatten(),
            ));
        }
    };
    let location = format!("/api/v1/documents/{id}");
    let created = match placement(body.parent_id, body.before_id) {
        Some(placement) => {
            store
                .create(NewItem::document(id, title, placement, markdown))
                .await?
        }
        None => Created::Existing(replayed(&store, id, ItemKind::Document).await?),
    };
    let document = Document::try_from(created.item().clone())?;
    Ok(created_response(&created, location, document))
}

/// Read a document's metadata and revision.
#[utoipa::path(
    get,
    path = "/documents/{documentId}",
    operation_id = "getDocument",
    tag = "documents",
    params(("documentId" = String, Path, description = "The document's identifier.")),
    responses(
        (status = 200, description = "The document.", body = Document),
        (
            status = 404,
            description = "No document has the identifier.",
            body = Problem,
            content_type = "application/problem+json"
        ),
        (
            status = 500,
            description = "The service failed unexpectedly.",
            body = Problem,
            content_type = "application/problem+json"
        ),
    )
)]
pub(crate) async fn get_document(
    State(store): State<Store>,
    Path(document_id): Path<String>,
) -> Result<Json<Document>, Problem> {
    let item = store
        .item(path_id(&document_id)?, domain::ItemKind::Document)
        .await?;
    Ok(Json(item.try_into()?))
}

/// Read a document's content and revision.
#[utoipa::path(
    get,
    path = "/documents/{documentId}/content",
    operation_id = "getDocumentContent",
    tag = "documents",
    params(("documentId" = String, Path, description = "The document's identifier.")),
    responses(
        (status = 200, description = "The document's content.", body = DocumentContent),
        (
            status = 404,
            description = "No document has the identifier.",
            body = Problem,
            content_type = "application/problem+json"
        ),
        (
            status = 500,
            description = "The service failed unexpectedly, or the stored content cannot be served.",
            body = Problem,
            content_type = "application/problem+json"
        ),
    )
)]
pub(crate) async fn get_document_content(
    State(store): State<Store>,
    Path(document_id): Path<String>,
) -> Result<Json<DocumentContent>, Problem> {
    let content = store.content(path_id(&document_id)?).await?;
    Ok(Json(DocumentContent {
        markdown: content.markdown.into_string(),
        revision: content.revision.as_str().to_owned(),
    }))
}

/// Save a document's whole content if it has not changed since
/// `baseRevision`.
#[utoipa::path(
    put,
    path = "/documents/{documentId}/content",
    operation_id = "replaceDocumentContent",
    tag = "documents",
    params(("documentId" = String, Path, description = "The document's identifier.")),
    request_body = ReplaceContentRequest,
    responses(
        (
            status = 200,
            description = "Saved the content, or found it already stored; the document carries the new revision.",
            body = Document
        ),
        (
            status = 404,
            description = "No document has the identifier.",
            body = Problem,
            content_type = "application/problem+json"
        ),
        (
            status = 409,
            description = "The stored content changed after `baseRevision`; nothing changed.",
            body = Problem,
            content_type = "application/problem+json"
        ),
        (
            status = 500,
            description = "The service failed unexpectedly, or the stored content cannot be served.",
            body = Problem,
            content_type = "application/problem+json"
        ),
        BodyProblems,
    )
)]
pub(crate) async fn replace_document_content(
    State(store): State<Store>,
    Path(document_id): Path<String>,
    Json(body): Json<ReplaceContentRequest>,
) -> Result<Json<Document>, Problem> {
    let id = path_id(&document_id)?;
    let markdown =
        Markdown::parse(body.markdown).map_err(|violation| Problem::violations([violation]))?;
    let document = store
        .replace_content(id, markdown, Revision::new(body.base_revision))
        .await?;
    Ok(Json(document.into()))
}

